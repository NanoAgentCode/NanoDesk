"""Regenerate the typed headless command table from registered desktop commands.
Run from the repository root. Native AppHandle/Webview/Channel adapters stay excluded.
"""
from pathlib import Path
import re
root=Path('src-tauri/src')
library=(root/'lib.rs').read_text(encoding='utf-8')
module_paths=dict((name,path) for path,name in re.findall(r'#\[path\s*=\s*"([^"]+)"\]\s*mod\s+(\w+);',library))
handler=library.split('tauri::generate_handler![',1)[1].split(']',1)[0]
entries=[];excluded=[]
for path in re.findall(r'([\w:]+)\s*(?:,|$)',handler):
 parts=path.split('::');name=parts[-1];mod=parts[:-1]
 source=root/module_paths.get(mod[0],mod[0]+'.rs')
 if not source.exists(): source=root/mod[0]/'mod.rs'
 for child in mod[1:]:
  directory=source.parent if source.name=='mod.rs' else source.with_suffix('')
  source=directory/(child+'.rs')
  if not source.exists(): source=directory/child/'mod.rs'
 if not source.exists(): excluded.append((path,'source path'));continue
 s=source.read_text(encoding='utf-8-sig')
 original_source=s
 match=re.search(r'pub(?:\([^)]*\))?\s+(async\s+)?fn\s+'+name+r'\s*\(',s)
 if not match: excluded.append((path,'signature'));continue
 end=s.index(')',match.end());raw=s[match.end():end]
 if any(token in raw for token in ['Webview','Channel<','Window<']) or mod[0] in ['desktop','document_chat']:
  excluded.append((path,'native app/events'));continue
 ret=s[end:s.index('{',end)]
 fallible = 'Result<' in ret
 if not fallible and name != 'fit_context_messages': excluded.append((path,'native return'));continue
 params=[];args=[];depth=0;begin=0;fields=[]
 for i,ch in enumerate(raw):
  if ch=='<':depth+=1
  elif ch=='>':depth-=1
  elif ch==',' and depth==0:fields.append(raw[begin:i].strip());begin=i+1
 fields.append(raw[begin:].strip());fields=[f for f in fields if f]
 for field in fields:
  key=field.split(':',1)[0].strip()
  if key=='app':args.append('host.clone()')
  elif key=='state':args.append('State::new(&state)')
  else: params.append(key);args.append(f'arg(params, "{key}")?')
 if 'State<' in raw:
  if 'use tauri::State;' in s: s=s.replace('use tauri::State;', 'use crate::app_state::CommandState as State;')
  else:
   def replace_import(m):
    fields=[x.strip() for x in m[1].split(',') if x.strip()!='State']
    return 'use tauri::{'+', '.join(fields)+'};\nuse crate::app_state::CommandState as State;'
   s=re.sub(r'use tauri::\{([^}]*\bState\b[^}]*)\};',replace_import,s)
  if s != original_source: source.write_text(s,encoding='utf-8')
 entries.append((path,name,params,args,bool(match[1]),fallible))
header='''//! Generated by scripts/generate-cli-business.py. Calls shared desktop domain commands.
use crate::{AppState, command_host::CommandHost, error::{AppError, AppResult}, app_state::CommandState as State};
use serde::de::DeserializeOwned;
use serde_json::Value;

fn arg<T: DeserializeOwned>(params: &Value, name: &str) -> AppResult<T> {
    serde_json::from_value(params.get(name).cloned().unwrap_or(Value::Null))
        .map_err(|error| AppError::from(format!("invalid argument {name}: {error}")))
}

pub(super) const COMMANDS: &[(&str, &[&str])] = &[
'''
header+=''.join('    ("'+name+'", &['+', '.join('"'+p+'"' for p in params)+']),\n' for path,name,params,args,async_,fallible in entries)+'];\n\n'
header+='''pub(crate) async fn dispatch(host: &CommandHost, command: &str, params: &Value) -> AppResult<Value> {
    let state = host.state::<AppState>();
    let parameters = COMMANDS.iter().find(|(name, _)| *name == command)
        .ok_or_else(|| AppError::from(format!("unknown CLI command: {command}")))?.1;
    let object = params.as_object().ok_or("command params must be a JSON object")?;
    for key in object.keys() {
        if !parameters.contains(&key.as_str()) { return Err(format!("unknown argument: {key}").into()); }
    }
    match command {
'''
for path,name,params,args,async_,fallible in entries:
 header+=f'        "{name}" => Ok(serde_json::to_value(crate::{path}({", ".join(args)})'+('.await' if async_ else '')+('?' if fallible else '')+')?),\n'
header+='        _ => unreachable!(),\n    }\n}\n\n#[cfg(test)]\n#[path = "business_tests.rs"]\nmod tests;\n'
(root/'cli/business.rs').write_text(header,encoding='utf-8')
Path('docs/05-开发运维/cli-command-coverage.json').write_text(__import__('json').dumps({'shared':[p for p,*_ in entries],'pending_or_native':[{'command':p,'reason':reason} for p,reason in excluded]},ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(f'{len(entries)} shared commands, {len(excluded)} require native/event adapters or exclusion.')
